"""单次试验的组装与执行（供 scripts/run_trial.py 与 scripts/run_matrix.py 共用）。"""

from __future__ import annotations

from dataclasses import asdict
from datetime import datetime
from pathlib import Path

import numpy as np

from .config import resolve_config
from .core.detector import FallDetector
from .core.recovery_fsm import RecoveryFSM
from .io.jitter import FallJitter
from .io.sim_backend import SimBackend
from .supervisor import Supervisor
from .utils.logger import TrialLogger

ROOT = Path(__file__).resolve().parents[1]


def run_trial(
    cfg: dict,
    fall: str,
    scene: str = "flat",
    run_dir: Path | None = None,
    video: Path | None = None,
    max_time: float = 60.0,
    jitter: FallJitter | None = None,
    seed: int | None = None,
    profile: str | None = None,
) -> dict:
    """注入翻倒姿态并跑完整恢复流程，返回结果与元数据。

    `profile=None` 时沿用配置中的 `sim.fall_profile`（默认 full_flip）；
    显式传 `nominal` 可复现旧版小幅翻倒。`jitter=None`（默认）为正式矩阵的
    确定性试验；传入 `FallJitter` 时用于 stress 套件，并通过 `seed` 保证
    单次试验可复现。
    """
    cfg = resolve_config(cfg, profile=profile)
    if fall == "trip" and scene == "flat":
        # 便于直接运行 --fall trip；该事件只能由路沿场景触发。
        scene = "trip"
    if fall == "trip" and scene != "trip":
        raise ValueError("fall='trip' requires scene='trip'")
    if fall == "trip":
        cfg["fsm"]["monitor_mode"] = "rl"
        cfg["fsm"]["post_fall_monitor_mode"] = "hold"
    backend = SimBackend(cfg["sim"], scene=scene)
    detector = FallDetector(cfg["detector"])
    fsm = RecoveryFSM(cfg["fsm"], detector)
    rng = np.random.default_rng(seed) if jitter is not None else None

    if fall in ("none", "stand"):
        backend.place_standing()
    elif fall == "trip":
        backend.place_trip()
    else:
        backend.place_fall(fall, jitter=jitter, rng=rng)

    logger = TrialLogger(run_dir) if run_dir is not None else None

    writer = None
    renderer = None
    frame_cb = None
    if video is not None:
        import imageio
        import mujoco

        writer = imageio.get_writer(str(video), fps=25, macro_block_size=None)
        renderer = mujoco.Renderer(backend.model, 720, 1280)
        option = mujoco.MjvOption()
        option.geomgroup[3] = 0  # 隐藏碰撞体，只留外观
        cam = mujoco.MjvCamera()
        cam.distance = 1.55
        cam.azimuth = 45
        cam.elevation = -18
        cam.lookat[:] = [0.03, 0.0, 0.25]

        def frame_cb(t: float) -> None:
            renderer.update_scene(backend.data, cam, scene_option=option)
            writer.append_data(renderer.render())

    sup = Supervisor(backend, detector, fsm, logger=logger, frame_cb=frame_cb)
    result = sup.run(
        max_time,
        det_hz=cfg["detector"]["rate_hz"],
        log_hz=cfg["logging"]["rate_hz"],
    )

    if writer is not None:
        writer.close()

    meta = {
        "run_id": run_dir.name if run_dir is not None else "",
        "date": datetime.now().isoformat(timespec="seconds"),
        "fall": fall,
        "fall_profile": cfg.get("active_profile", ""),
        "scene": scene,
        "model": "DeepRobotics Lite3 official MJCF (BSD-3), MuJoCo scene generated by scripts/build_scene.py; see sim/models/lite3/SOURCE.md",
        "config": {
            "detector": cfg["detector"],
            "fsm": cfg["fsm"],
            "sim": cfg["sim"],
        },
        "stress": (
            {"jitter": asdict(jitter), "seed": seed} if jitter is not None else None
        ),
        "result": result,
    }
    if logger is not None:
        logger.finish(meta)
    return result
